-- Esegui una sola volta nel SQL Editor di Supabase.
-- Le API server-side accedono alle tabelle con SUPABASE_SERVICE_ROLE_KEY.

alter table public.push_subscriptions
  add column if not exists nickname text;

create index if not exists push_subscriptions_nickname_idx
  on public.push_subscriptions (lower(nickname));

create table if not exists public.scheduled_notifications (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 80),
  body text not null check (char_length(body) between 1 and 180),
  target text not null default 'all' check (target in ('all', 'nickname')),
  nickname text,
  scheduled_at timestamptz not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'sent', 'failed')),
  sent_count integer,
  sent_at timestamptz,
  error_message text,
  created_at timestamptz not null default now(),
  check (target <> 'nickname' or nickname is not null)
);
create index if not exists scheduled_notifications_due_idx
  on public.scheduled_notifications (status, scheduled_at);
alter table public.scheduled_notifications enable row level security;
